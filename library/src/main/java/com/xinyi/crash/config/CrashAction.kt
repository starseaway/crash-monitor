package com.xinyi.crash.config

/**
 * 崩溃落盘与业务回调完成后的处理动作
 *
 * @author 杨耿雷
 * @date 2026/7/14 15:20
 */
enum class CrashAction {

    /**
     * 记录崩溃后结束当前进程
     *
     * 若开启崩溃界面，过渡模式下会先展示再退出；交互模式下由用户点击决定。
     */
    EXIT,

    /**
     * 记录崩溃后重启应用
     *
     * 若开启崩溃界面，过渡模式下会先展示再进入默认启动页；交互模式下由用户点击决定。
     * 若短时间内重启次数达到上限，会回退为 [EXIT]，避免崩溃循环。
     */
    RESTART,

    /**
     * 记录崩溃后交给被本框架替换掉的前一个未捕获异常处理器
     *
     * 不进入框架崩溃界面。
     */
    SYSTEM_DEFAULT
}